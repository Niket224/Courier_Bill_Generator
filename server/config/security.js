const { HASH_PATTERN } = require('../security/password');
function securityConfig(env) {
  const errors = [];
  if (!/^[A-Za-z0-9_.@-]{1,128}$/.test(env.ADMIN_USERNAME || '')) errors.push('ADMIN_USERNAME is required (1-128 letters, digits, _, ., @ or -).');
  if (!HASH_PATTERN.test(env.ADMIN_PASSWORD_HASH || '')) errors.push('ADMIN_PASSWORD_HASH must be generated by npm run admin:hash --prefix server.');
  if (typeof env.SESSION_SECRET !== 'string' || !/^[A-Za-z0-9_-]{43,128}$/.test(env.SESSION_SECRET)) errors.push('SESSION_SECRET must contain 43-128 random base64url characters.');
  if (!/^[A-Za-z0-9+/]{43}=$/.test(env.BROWSER_DRAFT_KEY || '') || Buffer.from(env.BROWSER_DRAFT_KEY || '', 'base64').length !== 32) errors.push('BROWSER_DRAFT_KEY is required: a separate persistent 32-byte base64 encryption key. Keep a protected recovery copy.');
  if (env.NODE_ENV === 'production') {
    if (new Set(env.SESSION_SECRET || '').size < 12 || /synthetic|example|changeme/i.test(env.SESSION_SECRET || '')) errors.push('SESSION_SECRET appears weak or is a test placeholder; generate a random secret.');
    if (new Set(Buffer.from(env.BROWSER_DRAFT_KEY || '', 'base64')).size < 12) errors.push('BROWSER_DRAFT_KEY appears weak; generate 32 random bytes.');
    if (env.BROWSER_DRAFT_KEY && Buffer.from(env.BROWSER_DRAFT_KEY, 'base64').equals(Buffer.from(env.SESSION_SECRET || '', 'base64url'))) errors.push('Browser and session keys must be independent.');
  }
  const age = env.SESSION_TTL_MINUTES ?? '480';
  if (!/^\d+$/.test(age) || Number(age) < 5 || Number(age) > 1440) errors.push('SESSION_TTL_MINUTES must be an integer from 5 to 1440.');
  if (!['false', 'loopback'].includes(env.TRUST_PROXY ?? 'false')) errors.push('TRUST_PROXY must be false or loopback.');
  if (errors.length) throw new Error(errors.join('\n- '));
  return { adminUsername: env.ADMIN_USERNAME, adminPasswordHash: env.ADMIN_PASSWORD_HASH,
    sessionSecret: env.SESSION_SECRET, browserDraftKey: env.BROWSER_DRAFT_KEY, sessionMaxAge: Number(age) * 60000,
    trustProxy: env.TRUST_PROXY === 'loopback' ? 'loopback' : false };
}
module.exports = { securityConfig };
